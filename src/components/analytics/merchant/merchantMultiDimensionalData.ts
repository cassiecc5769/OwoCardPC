export type MerchantDimensionKey = 'merchant' | 'tier' | 'brand' | 'sku' | 'region' | 'channel' | 'date';

export interface MerchantMultiDimensionalRow {
  id: string;
  name: string;
  code: string;
  tier: string;
  status: 'ONLINE' | 'WARNING' | 'STANDBY';
  creditLimitUsd: number;
  statusLabel?: string;
  coreCards: string[];
  ordersAccepted: number;
  ordersSuccess: number;
  ordersFailed: number;
  successRate: number;
  gmvUsd: number;
  gmvSharePercent: number;
  avgResponseSec: number;
  avgFulfillmentSec: number;
  rejectRatePercent: number;
  timeoutRatePercent: number;
  disputeRatePercent: number;
  actionType: 'balance' | 'downgrade' | 'dispatch';
  actionLabel: string;
  isWarning?: boolean;
  notes?: string;
}

export interface MerchantDrilldownOrder {
  orderId: string;
  merchantId: string;
  merchantName: string;
  cardName: string;
  faceValue: number;
  discountRate: number;
  durationSec: number;
  responseSec: number;
  createdAt: string;
  status: 'SUCCESS' | 'FAILED' | 'DISPUTE';
  statusLabel: string;
  pinMasked: string;
  operator: string;
  failureReason?: string;
}

