export type DimensionKey = 'brand' | 'sku' | 'merchant' | 'date' | 'channel';

export interface MultiDimensionalRowItem {
  id: string;
  dimension: DimensionKey;
  name: string;
  code: string;
  iconText: string;
  iconBg: string;
  iconColor: string;
  brand: string;
  geo: string;
  merchant?: string;
  channel?: string;
  submittedCount: number;
  successCount: number;
  failedCount: number;
  successRate: number; // e.g. 99.11
  submittedFaceValue: number; // USD
  settledGmv: number; // USD
  aov: number; // USD
  discountRate: number; // e.g. 7.0250
  avgDurationSec: number; // e.g. 24.2
  timeoutRate: number; // e.g. 0.31
  disputeRate: number; // e.g. 0.24
  isWarning?: boolean;
  warningTag?: string;
  statusText?: string;
}

export interface TrendPoint {
  date: string;
  gmv: number;
  orders: number;
  successRate: number;
  durationSec: number;
}

export interface DrilldownOrderRecord {
  orderId: string;
  skuCode: string;
  cardName: string;
  pinMasked: string;
  faceValue: number;
  settleUsd: number;
  discountRate: number;
  merchantName: string;
  channelName: string;
  status: 'SUCCESS' | 'FAILED' | 'DISPUTE' | 'PROCESSING';
  statusLabel: string;
  durationSec: number;
  createdAt: string;
  failureReason?: string;
  actionTaken?: string;
}

