export type FinancialDimensionKey = 'cardBrand' | 'region' | 'merchant' | 'channel';

export interface FinancialMultiDimensionalRow {
  id: string;
  name: string;
  subDesc: string;
  iconText: string;
  iconBg: string;
  iconColor: string;
  gmv: number;
  spreadAmount: number;
  spreadRatePercent: number;
  commissionAmount: number; // 负值 (如 -7200)
  subsidyAmount: number; // 负值 (如 -1440)
  badDebtAmount: number; // 负值 (如 -360)
  gatewayFee: number; // 负值 (如 -240)
  netProfit: number;
  netMarginPercent: number;
  profitContributionPercent: number;
  evaluationTag: string;
  evaluationColorClass: string;
  isRiskHigh?: boolean;
}

export interface FinancialL4OrderRow {
  orderId: string;
  timestamp: string;
  brand: string;
  denominationUsd: number;
  quotedDiscountRate: number; // 平台收卡折率 %
  merchantDiscountRate: number; // 商户承揽折率 %
  spreadProfitUsd: number;
  commissionDeduction: number;
  netProfitUsd: number;
  merchantName: string;
  buyerChannel: string;
  paymentGateway: string;
  status: 'AUDITED' | 'SETTLED' | 'PENDING' | 'DISPUTED';
}

